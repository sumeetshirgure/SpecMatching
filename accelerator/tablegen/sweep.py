#!/usr/bin/env python3
"""Table-size and latency sweep of the time-shift (delta-encoded, deduplicated) ball tables.

Usage:  sweep.py <hc_dump-binary> <out-dir> [--shots 10000] [--seed 20260903]

Runs `hc_dump --stats-only` for every (d, p) of the evaluation grid (d rounds each) and writes
<out-dir>/stats.csv (every key hc_dump reports, one row per point) and <out-dir>/table_sizes.md.
Latencies are hc_dump's register-level cycle model (cross-checked cycle-exact against the RTL by
accelerator/tests/run_crosscheck.sh), with the lane pipeline sized per shot as in sweep_dist/, for
both the new tables and the legacy layout (one full ball per detector, absolute targets) on the
same shots.

Standard library only.
"""

import csv
import os
import subprocess
import sys

DISTANCES = [17, 25, 31]
NOISES = [0.0005, 0.001, 0.003]
LANES = [16, 32, 64, 128]


def run_point(binary, out_dir, d, p, shots, seed):
    scratch = os.path.join(out_dir, "scratch")
    os.makedirs(scratch, exist_ok=True)
    out = subprocess.run(
        [binary, scratch, "--d", str(d), "--rounds", str(d), "--p", str(p), "--shots", str(shots),
         "--seed", str(seed), "--stats-only"],
        check=True, capture_output=True, text=True).stdout
    return dict(kv.split("=", 1) for kv in out.split())


def mbit(bits):
    return "%.2f" % (float(bits) / 1e6)


def write_md(rows, path, shots, seed):
    by = {(int(r["d"]), float(r["p"])): r for r in rows}
    lines = []
    w = lines.append
    w("# Time-shift ball tables: size and latency")
    w("")
    w("Generated by `accelerator/tablegen/sweep.py` (%d shots per point, seed %d; rotated surface code" % (shots, seed))
    w("memory-X, d rounds, uniform circuit noise p, T = T_max = 2 lattice edge weights, R = 2T).")
    w("")
    w("**Encoding.** A ball entry is `{w, delta = target - source}`. Rows are deduplicated only among")
    w("detectors at the same space coordinate, by exact comparison of their `{w, delta}` lists, and")
    w("entries with `target <= source` are dropped offline (`prune`). The boundary table carries each")
    w("detector's row pointer. *Legacy* is the previous layout: one full ball per detector with absolute")
    w("targets. Bits are logical (rows x word width), not padded to a power-of-two SRAM depth.")
    w("")
    w("## Table size (L = 64)")
    w("")
    w("| d | p | detectors | space positions | rows | rows / position | max row (legacy) | ball Mbit (legacy) | boundary Mbit (legacy) | total Mbit (legacy) | reduction |")
    w("|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|--:|")
    for d in DISTANCES:
        for p in NOISES:
            r = by[(d, p)]
            new_total = int(r["ball_bits"]) + int(r["bnd_bits"])
            old_total = int(r["legacy_ball_bits"]) + int(r["legacy_bnd_bits"])
            w("| %d | %g | %s | %s | %s | %.2f | %s (%s) | %s (%s) | %s (%s) | %s (%s) | %.2fx |" % (
                d, p, r["num_dets"], r["space_positions"], r["rows"],
                int(r["rows"]) / int(r["space_positions"]), r["max_row"], r["legacy_max_ball"],
                mbit(r["ball_bits"]), mbit(r["legacy_ball_bits"]),
                mbit(r["bnd_bits"]), mbit(r["legacy_bnd_bits"]),
                mbit(new_total), mbit(old_total), old_total / new_total))
    w("")
    w("The ball word is sized by the longest row, so `chunks_per_ball = ceil(max_row / L)`: %s at L = 64." %
      ", ".join("d=%d: %s (legacy %s)" % (d, by[(d, 0.001)]["chunks_per_ball"], by[(d, 0.001)]["legacy_chunks_per_ball"])
                for d in DISTANCES))
    w("")
    w("## Latency (cycles, mean / max over the shots, cycle model)")
    w("")
    w("Per-shot lane-pipeline depth `clog2(M + 1)`, as in `sweep_dist/`; a fixed-capacity instance adds")
    w("`clog2(cap + 1) - clog2(M + 1)` to both columns alike.")
    for p in NOISES:
        w("")
        w("### p = %g" % p)
        w("")
        w("| d \\ L | " + " | ".join(str(L) for L in LANES) + " |")
        w("|---|" + "---|" * len(LANES))
        for d in DISTANCES:
            r = by[(d, p)]
            cells = []
            for L in LANES:
                new, old = float(r["model_L%d_mean" % L]), float(r["legacy_L%d_mean" % L])
                cells.append("%.1f / %s (legacy %.1f / %s, %.2fx)" % (
                    new, r["model_L%d_max" % L], old, r["legacy_L%d_max" % L], old / new))
            w("| %d | %s |" % (d, " | ".join(cells)))
    w("")
    w("## Where the cycles go (L = 64, mean per shot)")
    w("")
    w("`fetch` is address-generator scan slots (one per chunk, at least one per defect); `drain` is the")
    w("collector's extra cycles for batches with more than one hit. Pruning halves `fetch` but packs the")
    w("same edges into fewer batches, so `drain` grows; at high p the collector, not the fetch, bounds")
    w("the latency.")
    w("")
    w("| d | p | mean M | fetch (legacy) | drain (legacy) |")
    w("|--:|--:|--:|--:|--:|")
    for d in DISTANCES:
        for p in NOISES:
            r = by[(d, p)]
            w("| %d | %g | %.1f | %.1f (%.1f) | %.1f (%.1f) |" % (
                d, p, float(r["mean_m"]), float(r["model_L64_fetch"]), float(r["legacy_L64_fetch"]),
                float(r["model_L64_drain"]), float(r["legacy_L64_drain"])))
    w("")
    with open(path, "w") as f:
        f.write("\n".join(lines))


def main():
    args = sys.argv[1:]
    if len(args) < 2:
        sys.exit(__doc__)
    binary, out_dir = args[0], args[1]
    shots, seed = 10000, 20260903
    rest = args[2:]
    while rest:
        k, v = rest[0], rest[1]
        rest = rest[2:]
        if k == "--shots":
            shots = int(v)
        elif k == "--seed":
            seed = int(v)
        else:
            sys.exit("unknown option " + k)
    os.makedirs(out_dir, exist_ok=True)
    rows = []
    for d in DISTANCES:
        for p in NOISES:
            print("d=%d p=%g" % (d, p), flush=True)
            rows.append(run_point(binary, out_dir, d, p, shots, seed))
    keys = list(rows[0].keys())
    with open(os.path.join(out_dir, "stats.csv"), "w", newline="") as f:
        wr = csv.DictWriter(f, fieldnames=keys)
        wr.writeheader()
        wr.writerows(rows)
    write_md(rows, os.path.join(out_dir, "table_sizes.md"), shots, seed)
    scratch = os.path.join(out_dir, "scratch")
    for name in os.listdir(scratch):
        os.remove(os.path.join(scratch, name))
    os.rmdir(scratch)


if __name__ == "__main__":
    main()
