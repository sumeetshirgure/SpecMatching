#!/usr/bin/env python3
"""Per-shot latency distribution of the legacy ball layout, from hc_dump's cycle model.

Usage:  sweep_dist.py <hc_dump-binary> <out-dir> [--shots 10000] [--seed 20260903]

Runs `hc_dump --stats-only --dist-csv` for every (d, p) of the evaluation grid (d rounds each) and
writes, into <out-dir>: dist_d<d>_p<p>.csv (one row per shot), dist_stats.csv (one row per
(d, p, lane count)) and latency_table_dist.md. Plots are a separate step, plot_dist.py.

The latency is hc_dump's register-level cycle model of the pipelined RTL, cross-checked cycle-exact
against it by accelerator/tests/run_crosscheck.sh, for the legacy layout (one full ball per
detector, absolute targets) at per-shot lane-pipeline capacity clog2(M + 1).

Standard library only.
"""

import csv
import math
import os
import subprocess
import sys

DISTANCES = [17, 25, 31]
NOISES = [0.0005, 0.001, 0.003]
LANES = [16, 32, 64, 128]

STATS_FIELDS = [
    "d",
    "p",
    "lanes",
    "n_shots",
    "mean_cycles",
    "std_cycles",
    "min_cycles",
    "median_cycles",
    "p95_cycles",
    "p99_cycles",
    "p999_cycles",
    "max_cycles",
    "mean_n_defects",
    "mean_edges",
    "mean_t_fetch",
    "mean_drain",
    "mean_h_exact",
    "zero_defect_shots",
]


def point_name(d, p):
    return "dist_d%d_p%g" % (d, p)


def run_point(binary, out_dir, d, p, shots, seed):
    """Run one grid point and return its per-shot rows."""
    scratch = os.path.join(out_dir, "scratch")
    os.makedirs(scratch, exist_ok=True)
    csv_path = os.path.join(out_dir, point_name(d, p) + ".csv")
    subprocess.run(
        [
            binary,
            scratch,
            "--d",
            str(d),
            "--rounds",
            str(d),
            "--p",
            str(p),
            "--shots",
            str(shots),
            "--seed",
            str(seed),
            "--stats-only",
            "--dist-csv",
            csv_path,
        ],
        check=True,
        capture_output=True,
        text=True,
    )
    with open(csv_path) as f:
        rows = [{k: int(v) for k, v in r.items()} for r in csv.DictReader(f)]
    if len(rows) != shots:
        sys.exit("%s: expected %d shots, got %d" % (csv_path, shots, len(rows)))
    return rows


def percentile(sorted_vals, q):
    """Linear interpolation between order statistics, the numpy.percentile default."""
    n = len(sorted_vals)
    if n == 1:
        return float(sorted_vals[0])
    pos = q * (n - 1)
    lo = int(math.floor(pos))
    hi = min(lo + 1, n - 1)
    return sorted_vals[lo] + (pos - lo) * (sorted_vals[hi] - sorted_vals[lo])


def stats_row(d, p, lanes, rows):
    cycles = sorted(r["cycles_L%d" % lanes] for r in rows)
    n = len(cycles)
    mean = sum(cycles) / n
    var = sum((c - mean) ** 2 for c in cycles) / (n - 1)  # sample, ddof = 1
    edges = sum(r["edges"] for r in rows) / n
    drain = sum(r["drain_L%d" % lanes] for r in rows) / n
    return {
        "d": d,
        "p": p,
        "lanes": lanes,
        "n_shots": n,
        "mean_cycles": "%.6f" % mean,
        "std_cycles": "%.6f" % math.sqrt(var),
        "min_cycles": cycles[0],
        "median_cycles": "%.6f" % percentile(cycles, 0.5),
        "p95_cycles": "%.6f" % percentile(cycles, 0.95),
        "p99_cycles": "%.6f" % percentile(cycles, 0.99),
        "p999_cycles": "%.6f" % percentile(cycles, 0.999),
        "max_cycles": cycles[-1],
        "mean_n_defects": "%.6f" % (sum(r["n_defects"] for r in rows) / n),
        "mean_edges": "%.6f" % edges,
        "mean_t_fetch": "%.6f" % (sum(r["fetch_L%d" % lanes] for r in rows) / n),
        "mean_drain": "%.6f" % drain,
        # batches that found at least one hit; the collector spends one cycle on each
        "mean_h_exact": "%.6f" % (edges - drain),
        "zero_defect_shots": sum(1 for r in rows if r["n_defects"] == 0),
    }


def check_point(d, p, rows):
    """`edges - drain_L` is the batch count, so drain must stay under a shot's edge count."""
    for r in rows:
        for lanes in LANES:
            batches = r["edges"] - r["drain_L%d" % lanes]
            if batches < 0 or (batches == 0 and r["edges"] > 0):
                sys.exit(
                    "d=%d p=%g shot %d: drain_L%d exceeds edges"
                    % (d, p, r["shot"], lanes)
                )


def write_md(stats, path, shots, seed):
    by = {(r["d"], r["p"], r["lanes"]): r for r in stats}
    lines = []
    w = lines.append
    w("# H-build latency distribution, legacy ball layout, pipelined RTL")
    w("")
    w(
        "Generated by `accelerator/tablegen/sweep_dist.py` (%d shots per point, seed %d; rotated"
        % (shots, seed)
    )
    w(
        "surface code memory-X, d rounds, uniform circuit noise p, T = T_max = 2 lattice edge weights,"
    )
    w("R = 2T). Plots: `accelerator/tablegen/plot_dist.py`.")
    w("")
    w(
        "**What these numbers are.** Every cell is an aggregate of `dist_stats.csv`, which is computed"
    )
    w(
        "from the per-shot files `dist_<point>.csv` in this directory and from nothing else. The"
    )
    w(
        "per-shot cycle counts come from `hc_dump --dist-csv`: the register-level replay of the"
    )
    w(
        "h_construct control path, for the *legacy* ball layout (one full ball per detector, absolute"
    )
    w(
        "targets) at per-shot lane-pipeline capacity `clog2(M + 1)`. The replay is not a closed form --"
    )
    w(
        "it models the address generator, the two push stages, the batch FIFO and its stall, the lane"
    )
    w(
        "pipeline and the collector -- and `accelerator/tests/run_crosscheck.sh` checks it cycle-exact"
    )
    w(
        "against the RTL it describes: the pipelined `h_construct` of commit 72ffb71 with the restored"
    )
    w(
        "`hc_fifo` `rd_v` declaration. No cell is RTL-measured at these (d, p); the RTL agreement is"
    )
    w("established at the cross-check point and the model is then evaluated here.")
    w("")
    w(
        "**This run supersedes the October 2026 run in this directory and shares no numbers with it.**"
    )
    w(
        "That run used a closed form, `cycles = 7 + clog2(max(M,1)+1) + t_fetch + (edges - H)`, against"
    )
    w(
        "the pre-pipeline RTL, and was produced by `latency_dist_bsearch.py`, which is not in this"
    )
    w(
        "repository on any branch. Its shot corpus cannot be reconstructed either: `hc_dump` at seed"
    )
    w(
        "%d draws a different sample. Both the model and the draw changed, so the two runs are not"
        % seed
    )
    w(
        "comparable cell by cell. The legacy columns of `accelerator/sweep_tshift/table_sizes.md` are"
    )
    w("the same model on the same grid and do agree with the means below.")
    w("")
    w(
        "**Caveats.** The capacity caveat: a deployed fixed-capacity instance pays `clog2(cap + 1)`"
    )
    w(
        "every shot instead of the per-shot `clog2(M + 1)`, which adds a constant to both columns"
    )
    w(
        "alike. The batch caveat: this is one seeded draw of %d shots per point, not an exact"
        % shots
    )
    w(
        "expectation. Zero-defect shots are counted in `dist_stats.csv`; the model reports 0 cycles for"
    )
    w("them.")
    w("")
    w(
        "Full per-shot distributions: `dist_<point>.csv` (per-lane `cycles`, `fetch` and `drain`, plus"
    )
    w(
        "the shot's defect and edge counts). Median, p95, p99 and max per cell: `dist_stats.csv`."
    )
    w("CCDFs: `latency_dist.png` / `.pdf`.")
    w("")
    w("---")
    w("")
    w("## Latency (cycles), %d shots per cell, model-derived" % shots)
    for p in NOISES:
        w("")
        w("### p = %g" % p)
        w("")
        w("Mean +- std (sample, ddof = 1):")
        w("")
        w("| d \\ LANES | " + " | ".join(str(L) for L in LANES) + " |")
        w("|---|" + "---|" * len(LANES))
        for d in DISTANCES:
            cells = [
                "%.3f +- %.2f"
                % (
                    float(by[(d, p, L)]["mean_cycles"]),
                    float(by[(d, p, L)]["std_cycles"]),
                )
                for L in LANES
            ]
            w("| %d | %s |" % (d, " | ".join(cells)))
        w("")
        w("Tails, p99 / p99.9:")
        w("")
        w("| d \\ LANES | " + " | ".join(str(L) for L in LANES) + " |")
        w("|---|" + "---|" * len(LANES))
        for d in DISTANCES:
            cells = [
                "%.1f / %.1f"
                % (
                    float(by[(d, p, L)]["p99_cycles"]),
                    float(by[(d, p, L)]["p999_cycles"]),
                )
                for L in LANES
            ]
            w("| %d | %s |" % (d, " | ".join(cells)))
    w("")
    w("## Where the cycles go (mean per shot)")
    w("")
    w(
        "`fetch` is address-generator scan slots (one per chunk, at least one per defect); `drain` is"
    )
    w(
        "the collector's extra cycles for batches with more than one hit, so `edges - drain` is the"
    )
    w("number of batches that found anything.")
    w("")
    w(
        "| d | p | mean M | mean edges | fetch L16 | drain L16 | fetch L128 | drain L128 |"
    )
    w("|--:|--:|--:|--:|--:|--:|--:|--:|")
    for d in DISTANCES:
        for p in NOISES:
            r16, r128 = by[(d, p, 16)], by[(d, p, 128)]
            w(
                "| %d | %g | %.1f | %.1f | %.1f | %.1f | %.1f | %.1f |"
                % (
                    d,
                    p,
                    float(r16["mean_n_defects"]),
                    float(r16["mean_edges"]),
                    float(r16["mean_t_fetch"]),
                    float(r16["mean_drain"]),
                    float(r128["mean_t_fetch"]),
                    float(r128["mean_drain"]),
                )
            )
    w("")
    with open(path, "w") as f:
        f.write("\n".join(lines))


def main():
    args = sys.argv[1:]
    if len(args) < 2:
        sys.exit(__doc__)
    binary, out_dir = args[0], args[1]
    shots, seed = 10000, 20260903
    rest = args[2:]
    while rest:
        k, v = rest[0], rest[1]
        rest = rest[2:]
        if k == "--shots":
            shots = int(v)
        elif k == "--seed":
            seed = int(v)
        else:
            sys.exit("unknown option " + k)
    os.makedirs(out_dir, exist_ok=True)
    stats = []
    for d in DISTANCES:
        for p in NOISES:
            print("d=%d p=%g" % (d, p), flush=True)
            rows = run_point(binary, out_dir, d, p, shots, seed)
            check_point(d, p, rows)
            for lanes in LANES:
                stats.append(stats_row(d, p, lanes, rows))
    with open(os.path.join(out_dir, "dist_stats.csv"), "w", newline="") as f:
        wr = csv.DictWriter(f, fieldnames=STATS_FIELDS)
        wr.writeheader()
        wr.writerows(stats)
    write_md(stats, os.path.join(out_dir, "latency_table_dist.md"), shots, seed)
    scratch = os.path.join(out_dir, "scratch")
    for name in os.listdir(scratch):
        os.remove(os.path.join(scratch, name))
    os.rmdir(scratch)


if __name__ == "__main__":
    main()
